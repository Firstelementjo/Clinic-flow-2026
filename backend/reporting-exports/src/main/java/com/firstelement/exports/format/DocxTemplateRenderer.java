    private void renderParagraph(XWPFDocument output, XWPFParagraph source,
                                 List<String> placeholders, Map<String, ReportField> byKey,
                                 RenderModel model, RenderStyle style) {
        String text = source.getText();
        List<String> segments = splitOnPlaceholders(text);
        // "One segment" is not the same as "no placeholder". A paragraph whose entire text is
        // "{{report.customer.displayName}}" splits into exactly one segment — the placeholder itself — and
        // treating that as literal writes the braces into the delivered document. The single-segment fast
        // path therefore has to exclude the case where the one segment IS a placeholder.
        if (segments.size() == 1 && !PLACEHOLDER.matcher(segments.get(0)).matches()) {
            // A literal paragraph: keep its text, re-create its direction, and carry a heading style
            // across so a template's structure survives.
            XWPFParagraph paragraph = output.createParagraph();
            applyParagraphDirection(paragraph, style);
            if (source.getStyle() != null) {
                paragraph.setStyle(source.getStyle());
            }
            appendTextRun(paragraph, text, style, source.getRuns().isEmpty() ? null : bold(source));
            return;
        }
        XWPFParagraph paragraph = output.createParagraph();
        applyParagraphDirection(paragraph, style);
        if (source.getStyle() != null) {
            paragraph.setStyle(source.getStyle());
        }
        for (String segment : segments) {
            if (segment.isEmpty()) {
                continue;
            }
            Matcher matcher = PLACEHOLDER.matcher(segment);
            if (matcher.matches()) {
                appendBoundRun(paragraph, matcher.group(1), matcher.group(2), byKey, model, style);
            } else {
                appendTextRun(paragraph, segment, style, null);
            }
        }
    }

    private void renderTable(XWPFDocument output, XWPFTable source,
                             List<String> placeholders, Map<String, ReportField> byKey,
                             RenderModel model, RenderStyle style) {
        // A two-row template table is the header plus the body marker. The header row's labels are taken
        // from the template (so the tenant's wording is honoured); the body rows are generated from the
        // model. A one-row table is all header.
        boolean hasMarker = containsRowMarker(source, placeholders);
        List<XWPFTableRow> sourceRows = source.getRows();
        int headerRows = hasMarker ? 1 : sourceRows.size();

        // The output table is sized to the HEADER rows only. Sizing it to the source row count would carry
        // the body-marker row into the delivered document as a row of literal "{{report.…}}" text, which
        // is both a visible artefact of the templating and a second, unbound copy of every field name.
        XWPFTable table = output.createTable(Math.max(1, headerRows), 1);
        // getTableAlignment() returns null when the template set no alignment, and setTableAlignment(null)
        // dereferences it — so an Arabic template authored without an explicit alignment would fail on the
        // very first table. The direction the report declares is applied instead of the template's null.
        TableRowAlign alignment = source.getTableAlignment() != null
            ? source.getTableAlignment()
            : (style.rightToLeft() ? TableRowAlign.RIGHT : TableRowAlign.LEFT);
        table.setTableAlignment(alignment);
        for (XWPFTableRow row : table.getRows()) {
            for (XWPFTableCell cell : row.getTableCells()) {
                cell.setColor(null);
            }
        }
        // A visible single-pixel border around the whole grid: without it a generated table reads as
        // floating text in some viewers, which is the most common complaint about an exported report.
        applyGridBorders(table);

        for (int r = 0; r < headerRows; r++) {
            XWPFTableRow target = table.getRow(r);
            copyRowCells(sourceRows.get(r), target, placeholders, byKey, model, style, true);
        }

        if (!hasMarker) {
            return;
        }
        // The marker row is the row AFTER the header, not the header itself. Reading headerRows - 1 here
        // binds the header's own labels — which contain no placeholders — so every generated row came out
        // empty while the table still looked structurally correct.
        XWPFTableRow markerRow = sourceRows.get(headerRows);
        List<String> bodyKeys = bodyKeysOf(markerRow, placeholders);
        int index = 0;
        for (Map<String, Object> row : model.rowValues()) {
            XWPFTableRow tableRow = table.createRow();
            copyHeaderCellStyle(markerRow, tableRow, 0);
            for (String key : bodyKeys) {
                XWPFTableCell cell = tableRow.getCell(Math.min(index, tableRow.getTableCells().size() - 1));
                if (cell == null) {
                    cell = tableRow.addNewTableCell();
                }
                // The cell's paragraph is used as-is rather than cleared with setText(""): POI's setText
                // drops the paragraph it is given an empty string for on some versions, and the run then
                // lands nowhere, which is how a generated body row came out empty.
                XWPFParagraph cellParagraph = cell.getParagraphs().isEmpty()
                    ? cell.addParagraph() : cell.getParagraphs().get(0);
                applyParagraphDirection(cellParagraph, style);
                appendBoundRun(cellParagraph, "report", key, byKey, model, style);
                index++;
            }
            // Any remaining marker cells in the template row are dropped from the generated rows: a
            // column the body marker never named has no data, and an empty cell would read as "no value".
        }
        if (table.getNumberOfRows() > headerRows && model.rowValues().isEmpty()) {
            // No rows: leave the header alone. A document with a header and nothing under it is an honest
            // empty report; a header plus a row of blanks is not.
            removeTrailingEmptyRows(table, headerRows);
        }
    }

    private void copyRowCells(XWPFTableRow source, XWPFTableRow target, List<String> placeholders,
                              Map<String, ReportField> byKey, RenderModel model, RenderStyle style,
                              boolean header) {
        int index = 0;
        for (XWPFTableCell sourceCell : source.getTableCells()) {
            XWPFTableCell cell = target.getCell(index);
            if (cell == null) {
                cell = target.addNewTableCell();
            }
            cell.setText("");
            XWPFParagraph paragraph = cell.getParagraphs().isEmpty()
                ? cell.addParagraph() : cell.getParagraphs().get(0);
            applyParagraphDirection(paragraph, style);
            String cellText = sourceCell.getText();
            // Deliberately NOT cell.setText("") first: on some POI versions an empty setText removes the
            // paragraph the run is about to be added to, which is how a header cell came out empty.
            for (String segment : splitOnPlaceholders(cellText)) {
                if (segment.isEmpty()) {
                    continue;
                }
                Matcher matcher = PLACEHOLDER.matcher(segment);
                if (matcher.matches()) {
                    appendBoundRun(paragraph, matcher.group(1), matcher.group(2), byKey, model, style);
                } else {
                    appendTextRun(paragraph, segment, style, null);
                }
            }
            index++;
        }
    }

    private void copyHeaderCellStyle(XWPFTableRow sourceRow, XWPFTableRow targetRow, int cellIndex) {
        if (sourceRow.getTableCells().isEmpty()) {
            return;
        }
        XWPFTableCell source = sourceRow.getTableCells().get(0);
        XWPFTableCell target = targetRow.getTableCells().isEmpty()
            ? null : targetRow.getTableCells().get(cellIndex);
        if (target == null) {
            return;
        }
        target.setColor(source.getColor() == null ? null : source.getColor());
    }

    private boolean containsRowMarker(XWPFTable table, List<String> placeholders) {
        for (XWPFTableRow row : table.getRows()) {
            for (XWPFTableCell cell : row.getTableCells()) {
                String text = cell.getText();
                Matcher matcher = PLACEHOLDER.matcher(text == null ? "" : text);
                while (matcher.find()) {
                    if ("report".equals(matcher.group(1))) {
                        return true;
                    }
                }
            }
        }
        return false;
    }

    /** The field keys the body marker row names, in cell order. */
    private List<String> bodyKeysOf(XWPFTableRow markerRow, List<String> placeholders) {
        List<String> keys = new ArrayList<>();
        for (XWPFTableCell cell : markerRow.getTableCells()) {
            Matcher matcher = PLACEHOLDER.matcher(cell.getText() == null ? "" : cell.getText());
            if (matcher.find() && "report".equals(matcher.group(1))) {
                keys.add(matcher.group(2));
            }
        }
        return keys;
    }

    private void removeTrailingEmptyRows(XWPFTable table, int keep) {
        for (int r = table.getNumberOfRows() - 1; r >= keep; r--) {
            try {
                table.removeRow(r);
            } catch (RuntimeException e) {
                // The table refuses to shrink past a structural minimum. Leaving the rows is cosmetic;
                // throwing would fail a job over a rendering detail, which is the wrong trade.
                return;
            }
        }
    }

