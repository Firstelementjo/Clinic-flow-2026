    /**
     * Marks a paragraph right-to-left.
     *
     * <p>{@code w:bidi} on {@code w:pPr}. Without it the paragraph lays out left-to-right even when every
     * run is marked RTL, so an Arabic label sits at the wrong end of the line with the punctuation
     * mirrored.
     */
    void applyParagraphDirection(XWPFParagraph paragraph, RenderStyle style) {
        if (!style.rightToLeft()) {
            return;
        }
        // getPPr() is null for a paragraph created with no properties, which is every paragraph this class
        // creates and every cell paragraph POI hands back. addNewBidi() on a null CTPPr is a NullPointer
        // Exception, so the properties element has to be created first. Without this an Arabic export of
        // an ordinary template throws on its first paragraph — a defect that only the RTL suite finds.
        if (paragraph.getCTP().getPPr() == null) {
            paragraph.getCTP().addNewPPr();
        }
        paragraph.getCTP().getPPr().addNewBidi().setVal(true);
        // The paragraph MARK is also marked RTL, so a caret placed at the end of the paragraph behaves
        // the way an Arabic writer expects. CTParaRPr spells the element `rtl` (lowercase), which is why
        // this is set through the generated setter rather than through addNewRTL().
        if (paragraph.getCTP().getPPr().getRPr() == null) {
            paragraph.getCTP().getPPr().addNewRPr();
        }
        paragraph.getCTP().getPPr().getRPr().addNewRtl().setVal(true);
    }

    /**
     * Writes a literal text run and, for an RTL document, marks the run RTL.
     *
     * <p>The complex-script font family is set as well as {@code w:rtl}: a run flagged RTL but rendered
     * with a Latin-only font falls back per-glyph, which is how Arabic ends up with disconnected
     * letterforms in an otherwise correct document.
     */
    void appendTextRun(XWPFParagraph paragraph, String text, RenderStyle style, Boolean bold) {
        if (text == null || text.isEmpty()) {
            return;
        }
        XWPFRun run = paragraph.createRun();
        run.setText(text);
        if (bold != null && bold) {
            run.setBold(true);
        }
        if (style.rightToLeft()) {
            markRunRtl(run);
        }
    }

    /** Marks one run as right-to-left and gives it a complex-script font. */
    void markRunRtl(XWPFRun run) {
        // getRPr() is null on a run created by createRun() with no formatting, which is every run this
        // class writes before it adds one. Same shape as the paragraph case: create the properties element
        // before adding the mark to it.
        if (run.getCTR().getRPr() == null) {
            run.getCTR().addNewRPr();
        }
        run.getCTR().getRPr().addNewRtl().setVal(true);
        // A font that covers Arabic, applied to the complex-script range rather than the Latin range.
        run.setFontFamily("Arial", XWPFRun.FontCharRange.cs);
    }

    private void appendBoundRun(XWPFParagraph paragraph, String namespace, String key,
                                Map<String, ReportField> byKey, RenderModel model, RenderStyle style) {
        String value = resolve(namespace, key, byKey, model);
        XWPFRun run = paragraph.createRun();
        run.setText(value);
        run.setBold(true);
        if (style.rightToLeft()) {
            markRunRtl(run);
        }
    }

    /** The string a placeholder renders to. */
    private String resolve(String namespace, String key, Map<String, ReportField> byKey,
                           RenderModel model) {
        return switch (namespace) {
            case "meta" -> model.meta().getOrDefault(key, ExportValueFormatter.ABSENT);
            case "totals" -> {
                BigDecimal total = model.totals().get(key);
                yield total == null ? ExportValueFormatter.ABSENT
                    : ExportValueFormatter.machine(byKey.get(key), total,
                        java.util.Locale.ENGLISH, java.time.ZoneOffset.UTC);
            }
            default -> {
                if (model.rowValues().isEmpty()) {
                    yield ExportValueFormatter.ABSENT;
                }
                ReportField field = byKey.get(key);
                Object raw = model.rowValues().get(0).get(key);
                yield field == null ? ExportValueFormatter.ABSENT
                    : ExportValueFormatter.document(field, raw,
                        styleLocale(model), styleZone(model));
            }
        };
    }

    private static Locale styleLocale(RenderModel model) {
        String locale = model.meta().get("locale");
        return locale == null ? Locale.ENGLISH : Locale.forLanguageTag(locale);
    }

    private static ZoneId styleZone(RenderModel model) {
        String zone = model.meta().get("timezone");
        return zone == null ? ZoneId.of("UTC") : ZoneId.of(zone);
    }

    /** Splits a paragraph's text into literal and placeholder segments, dropping the braces. */
    static List<String> splitOnPlaceholders(String text) {
        if (text == null || text.isEmpty()) {
            return List.of();
        }
        List<String> segments = new ArrayList<>();
        int cursor = 0;
        Matcher matcher = PLACEHOLDER.matcher(text);
        while (matcher.find()) {
            if (matcher.start() > cursor) {
                segments.add(text.substring(cursor, matcher.start()));
            }
            segments.add(matcher.group());
            cursor = matcher.end();
        }
        if (cursor < text.length()) {
            segments.add(text.substring(cursor));
        }
        return segments;
    }

    /** The declared metadata placeholder names, so the authoring surface can offer exactly these. */
    public static List<String> metaNames() {
        return List.copyOf(META.keySet());
    }

    /** The Arabic label for a metadata name. */
    public static String metaLabelAr(String name) {
        MetaBinder binder = META.get(name);
        return binder == null ? name : binder.labelAr();
    }

    /** The English label for a metadata name. */
    public static String metaLabelEn(String name) {
        MetaBinder binder = META.get(name);
        return binder == null ? name : binder.labelEn();
    }

    private static void applyGridBorders(XWPFTable table) {
        var properties = table.getCTTbl().getTblPr();
        if (properties.isSetTblBorders()) {
            return;
        }
        var borders = properties.addNewTblBorders();
        for (String edge : new String[] {"top", "left", "bottom", "right", "insideH", "insideV"}) {
            var border = switch (edge) {
                case "top" -> borders.addNewTop();
                case "left" -> borders.addNewLeft();
                case "bottom" -> borders.addNewBottom();
                case "right" -> borders.addNewRight();
                case "insideH" -> borders.addNewInsideH();
                default -> borders.addNewInsideV();
            };
            border.setVal(STBorder.SINGLE);
            // Sizes are eighths of a point and are typed BigInteger by the OOXML schema.
            border.setSz(java.math.BigInteger.valueOf(4));
            border.setSpace(java.math.BigInteger.ZERO);
            border.setColor("BFBFBF");
        }
    }

    private static Boolean bold(XWPFParagraph paragraph) {
        return paragraph.getRuns().stream().anyMatch(XWPFRun::isBold) ? Boolean.TRUE : null;
    }

    /**
     * A page break appended to a paragraph, for a template that needs one.
     *
     * <p>{@code BreakClear.ALL} rather than a bare break so the break does not inherit the source
     * paragraph's formatting, which is how an exported report ends up with a page break rendered in
     * eight-point bold.
     */
    public static void appendPageBreak(XWPFParagraph paragraph) {
        XWPFRun run = paragraph.createRun();
        run.addBreak(BreakClear.ALL);
    }

