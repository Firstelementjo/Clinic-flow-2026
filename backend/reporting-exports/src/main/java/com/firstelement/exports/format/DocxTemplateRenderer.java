            + "governed by the tenant's retention and legal-hold policy.";

    /** One metadata placeholder: its two labels and how its value is rendered. */
    private record MetaBinder(String labelAr, String labelEn, MetaKind kind) {
    }

    private enum MetaKind {
        TEXT,
        DATE_TIME,
        INTEGER
    }

    /**
     * The values a render binds, already reduced and formatted.
     *
     * @param rowValues   one map per rendered row, keyed by the field key
     * @param totals      summed measures, keyed by the field key. Pre-computed by the caller from the
     *                    same rows so the printed total and the printed table cannot disagree.
     * @param meta        the metadata values, keyed by the reserved names above
     */
    public record RenderModel(List<Map<String, Object>> rowValues,
                              Map<String, BigDecimal> totals,
                              Map<String, String> meta) {

        public RenderModel {
            rowValues = List.copyOf(rowValues);
            totals = Map.copyOf(totals);
            meta = Map.copyOf(meta);
        }
    }

    /** The locale and timezone a document renders in, taken from the report definition. */
    public record RenderStyle(Locale locale, ZoneId timezone, boolean rightToLeft) {

        /** The style implied by a locale: Arabic renders RTL, everything else LTR. */
        public static RenderStyle of(Locale locale, String timezone) {
            boolean rtl = com.firstelement.exports.catalog.ReportField.isArabic(locale.toLanguageTag());
            return new RenderStyle(locale, ZoneId.of(timezone == null ? "UTC" : timezone), rtl);
        }
    }

    /**
     * Renders a document.
     *
     * @param templateBytes the stored template. Parsed, never executed.
     * @param approvedFields the report version's <em>emitted</em> fields. A placeholder naming anything
     *                       else fails the job.
     * @param model         the values
     * @param style         locale, timezone and direction
     * @param sink          the destination. Written, not closed.
     */
    public void render(byte[] templateBytes,
                       List<ReportField> approvedFields,
                       RenderModel model,
                       RenderStyle style,
                       OutputStream sink) throws IOException {
        Set<String> approved = new LinkedHashSet<>();
        Map<String, ReportField> byKey = new LinkedHashMap<>();
        for (ReportField field : approvedFields) {
            approved.add(field.key());
            byKey.put(field.key(), field);
        }

        // Phase one: validate EVERY placeholder in the template against the approved set, before writing
        // a single byte. Validating during the write would leave a half-rendered document in the sink on
        // failure, and a partial document that gets stored is worse than no document.
        try (XWPFDocument source = new XWPFDocument(new ByteArrayInputStream(templateBytes))) {
            List<String> placeholders = extractPlaceholders(source, approved);

            try (XWPFDocument output = new XWPFDocument()) {

                output.getDocument().getBody().setSectPr(source.getDocument().getBody().getSectPr());

                for (XWPFParagraph paragraph : source.getParagraphs()) {
                    renderParagraph(output, paragraph, placeholders, byKey, model, style);
                }
                for (XWPFTable table : source.getTables()) {
                    renderTable(output, table, placeholders, byKey, model, style);
                }
                if (source.getParagraphs().isEmpty() && source.getTables().isEmpty()) {
                    throw DocxTemplateException.unsupportedMedia(
                        "the stored template has no paragraph and no table, so there is nothing to render "
                            + "into");
                }

                output.write(sink);
            }
        }
    }

    /**
     * Collects every placeholder name in the template and refuses the unapproved ones.
     *
     * <p>Reads the template's <em>paragraph and cell text</em>, not the template's bytes. A DOCX is a ZIP:
     * its {@code word/document.xml} is deflated, so scanning the raw bytes for {@code {{report.…}}}
     * finds nothing in a template Word itself produced and the whole gate silently passes — which is
     * precisely the failure this method exists to prevent, arrived at by reading the wrong thing. The
     * body text is also the only place a placeholder can be, so this both finds all of them and misses
     * none. The malformed-brace check runs over the same text for the same reason.
     */
    private List<String> extractPlaceholders(XWPFDocument source, Set<String> approved) {
        List<String> names = new ArrayList<>();
        List<String> texts = new ArrayList<>();
        for (XWPFParagraph paragraph : source.getParagraphs()) {
            texts.add(paragraph.getText());
        }
        for (XWPFTable table : source.getTables()) {
            for (XWPFTableRow row : table.getRows()) {
                for (XWPFTableCell cell : row.getTableCells()) {
                    texts.add(cell.getText());
                }
            }
        }
        for (String text : texts) {
            Matcher matcher = PLACEHOLDER.matcher(text == null ? "" : text);
            while (matcher.find()) {
                names.add(matcher.group(1) + "." + matcher.group(2));
            }
        }
        if (texts.stream().anyMatch(text -> EMPTY_PLACEHOLDER.matcher(text == null ? "" : text).find())) {
            throw DocxTemplateException.malformedPlaceholder(
                "'{{}}' names no field; a placeholder must be {{report.<key>}}, {{meta.<name>}} or "
                    + "{{totals.<key>}}");
        }
        for (String name : names) {
            String namespace = name.substring(0, name.indexOf('.'));
            String key = name.substring(name.indexOf('.') + 1);
            switch (namespace) {
                case "meta" -> {
                    if (!META.containsKey(key)) {
                        throw DocxTemplateException.malformedPlaceholder(
                            "'" + name + "' is not a declared metadata name. Declared names are "
                                + String.join(", ", META.keySet()));
                    }
                }
                default -> {
                    // Both "report." and "totals." resolve against the same approved set. A key that is
                    // in the registry but withheld from this caller is absent from `approved`, which is
                    // what closes the redaction bypass: a template cannot reach a field the caller may
                    // not see, however the field was withheld.
                    if (!approved.contains(key)) {
                        throw DocxTemplateException.unapprovedField(name);
                    }
                }
            }
        }
        return List.copyOf(names);
    }

